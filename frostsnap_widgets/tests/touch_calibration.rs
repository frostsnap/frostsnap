#[test]
fn matches_f32_on_every_panel_column() {
    for (x, &expected) in F32_X_ADJUSTMENT.iter().enumerate() {
        assert_eq!(x_based_adjustment(x as i32), expected, "x = {x}");
    }
}

#[test]
fn matches_f32_on_every_panel_row() {
    for (y, &expected) in F32_Y_ADJUSTMENT.iter().enumerate() {
        assert_eq!(y_based_adjustment(y as i32), expected, "y = {y}");
    }
    for y in 171..280 {
        assert_eq!(y_based_adjustment(y), 0, "y = {y}");
    }
}

#[test]
fn out_of_panel_input_is_bounded() {
    assert_eq!(x_based_adjustment(4095), x_based_adjustment(255));
    assert_eq!(y_based_adjustment(-5), y_based_adjustment(0));
}
